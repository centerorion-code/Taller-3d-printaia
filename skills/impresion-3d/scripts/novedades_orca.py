"""Novedades de Orca: qué parámetros aparecieron o desaparecieron, y qué ya no se usa.

El taller conoce los parámetros de OrcaSlicer 2.5.1 (catálogo y lista de claves que Orca escribe
en el G-code). Esto compara contra lo que usa de verdad el Orca del usuario y guarda lo visto en un
archivo de estado de la carpeta de trabajo, para avisar solo lo que cambió desde la última vez.

Uso:
  # Después de laminar: ¿el Orca del usuario tiene parámetros nuevos o le faltan algunos?
  python3 novedades_orca.py gcode plate_1.gcode --estado novedades-orca.json

  # Perfiles de usuario: claves que Orca ya no usa, perfiles TEST viejos, AUTO de impresoras que no están
  python3 novedades_orca.py perfiles <carpeta process> <carpeta filament> [--config config.json] [--maquinas <carpeta machine>]

  # ¿Toca revisar en la web si hay Orca o plugins nuevos? (cada 30 días)
  python3 novedades_orca.py web --estado novedades-orca.json [--marcar "Orca 2.5.1 sigue siendo la última"]

Código de salida: 0 sin novedades, 1 hay algo para contar.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comun  # noqa: E402

BASE_GCODE = comun.DATOS / f"claves-gcode-{comun.VERSION_ORCA}.json"
RE_VERSION = re.compile(r"generated by OrcaSlicer\s+([0-9][0-9A-Za-z.\-]*)")
RE_CLAVE = re.compile(r"^; ([a-z0-9_]+) = ", re.M)
META = {"from", "inherits", "is_custom_defined", "name", "version", "print_settings_id",
        "filament_settings_id", "printer_settings_id", "setting_id", "base_id", "instantiation",
        "compatible_printers", "compatible_printers_condition", "compatible_prints",
        "compatible_prints_condition", "filament_id", "user_id", "updated_time", "type",
        "printer_model", "printer_variant", "default_print_profile", "default_filament_profile"}
DIAS_WEB = 30
DIAS_TEST = 30


def hoy() -> str:
    return dt.date.today().isoformat()


def cargar_estado(ruta: Path | None) -> dict:
    if ruta and ruta.exists():
        return comun.cargar_json(ruta)
    return {"claves_nuevas": {}, "claves_quitadas": {}, "versiones_vistas": {}}


def guardar_estado(ruta: Path | None, estado: dict) -> None:
    if ruta:
        ruta.parent.mkdir(parents=True, exist_ok=True)
        ruta.write_text(json.dumps(estado, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def leer_gcode(ruta: Path) -> tuple[str | None, set[str]]:
    texto = ruta.read_text(encoding="utf-8", errors="replace")
    m = RE_VERSION.search(texto[:4000])
    ini, fin = texto.rfind("; CONFIG_BLOCK_START"), texto.rfind("; CONFIG_BLOCK_END")
    if ini < 0 or fin < ini:
        raise SystemExit("El G-code no tiene el bloque de configuración de Orca (CONFIG_BLOCK).")
    return (m.group(1) if m else None), set(RE_CLAVE.findall(texto[ini:fin]))


def revisar_gcode(ruta: Path, estado: dict) -> dict:
    version, claves = leer_gcode(ruta)
    base = set(comun.cargar_json(BASE_GCODE)["claves"])
    catalogo = comun.cargar_catalogo()
    nuevas = sorted(claves - base - set(catalogo))
    quitadas = sorted(base - claves)
    cuando = f"{hoy()} (Orca {version or '?'})"
    antes_nuevas, antes_quitadas = set(estado.get("claves_nuevas", {})), set(estado.get("claves_quitadas", {}))
    for c in nuevas:
        estado.setdefault("claves_nuevas", {}).setdefault(c, cuando)
    for c in quitadas:
        estado.setdefault("claves_quitadas", {}).setdefault(c, cuando)
    if version:
        estado.setdefault("versiones_vistas", {}).setdefault(version, hoy())
    estado["version_orca"] = version
    estado["ultima_revision_gcode"] = hoy()
    return {
        "version_orca": version,
        "version_taller": comun.VERSION_ORCA,
        "otra_version": bool(version) and version != comun.VERSION_ORCA,
        "claves_nuevas": nuevas,
        "claves_quitadas": quitadas,
        "nuevas_desde_la_ultima_vez": sorted(set(nuevas) - antes_nuevas),
        "quitadas_desde_la_ultima_vez": sorted(set(quitadas) - antes_quitadas),
    }


def _perfiles(rutas: list[Path]) -> list[Path]:
    archivos = []
    for r in rutas:
        archivos += sorted(r.glob("*.json")) if r.is_dir() else [r]
    return [a for a in archivos if a.suffix == ".json"]


def _actualizado(archivo: Path, perfil: dict) -> dt.date | None:
    valor = perfil.get("updated_time")
    info = archivo.with_suffix(".info")
    if not valor and info.exists():
        m = re.search(r"updated_time\s*=\s*(\d+)", info.read_text(encoding="utf-8", errors="replace"))
        valor = m.group(1) if m else None
    try:
        return dt.datetime.fromtimestamp(int(valor)).date() if valor else None
    except (TypeError, ValueError, OSError):
        return None


def revisar_perfiles(rutas: list[Path], config: dict | None, maquinas: list[Path] | None = None) -> dict:
    catalogo = comun.cargar_catalogo()
    base = set(comun.cargar_json(BASE_GCODE)["claves"])
    conocidas = set(catalogo) | base | META
    configuradas = [i for i in (config or {}).get("impresoras", []) if isinstance(i, dict)]
    impresoras = {i["perfil_maquina"] for i in configuradas if isinstance(i.get("perfil_maquina"), str)}
    patrones = {comun.plano(x) for i in configuradas for x in (i.get("patron_perfiles"), i.get("nombre_corto"),
                                                                i.get("nombre")) if isinstance(x, str) and x.strip()}
    # Las copias de usuario de máquina también son impresoras presentes, aunque no estén preparadas en el taller.
    for archivo in _perfiles(maquinas or []):
        try:
            datos = comun.cargar_json(archivo)
        except (json.JSONDecodeError, UnicodeDecodeError, OSError):
            continue
        if isinstance(datos, dict):
            impresoras.update(datos[k] for k in ("name", "inherits") if isinstance(datos.get(k), str) and datos[k])
    presentes = {comun.plano(comun.modelo_de_perfil(x)) for x in impresoras if x}

    def tiene_impresora(destino: str) -> bool:
        """¿Hay una impresora presente para ese @destino? Tiene que ser el mismo modelo o su final completo:
        @K1 no es la K1 Max, @A1 no es la A1 mini."""
        d = comun.plano(comun.modelo_de_perfil(destino))
        return bool(d) and (d in patrones or d in presentes or any(m.endswith(" " + d) for m in presentes))
    en_config = set()
    for imp in (config or {}).get("impresoras", []):
        for valor in imp.values():
            if isinstance(valor, str):
                en_config.add(valor)
            elif isinstance(valor, dict):
                en_config.update(v for v in valor.values() if isinstance(v, str))
    obsoletas, viejos, huerfanos, ilegibles = {}, [], [], []
    for archivo in _perfiles(rutas):
        try:
            perfil = comun.cargar_json(archivo)
        except (json.JSONDecodeError, UnicodeDecodeError, OSError):
            ilegibles.append(archivo.name)
            continue
        nombre = str(perfil.get("name") or archivo.stem)
        sobran = sorted(k for k in perfil if k not in conocidas)
        if sobran:
            obsoletas[nombre] = sobran
        fecha = _actualizado(archivo, perfil)
        if nombre.startswith("TEST ") and fecha and (dt.date.today() - fecha).days > DIAS_TEST:
            viejos.append(f"{nombre} (último cambio {fecha.isoformat()})")
        if config and nombre.startswith("AUTO ") and "@" in nombre and nombre not in en_config:
            if not tiene_impresora(nombre.split("@", 1)[1]):
                huerfanos.append(nombre)
    return {"claves_que_orca_no_usa": obsoletas, "test_viejos": viejos,
            "auto_sin_impresora": huerfanos, "ilegibles": ilegibles}


def revisar_web(estado: dict, marcar: str | None) -> dict:
    ultima = estado.get("ultima_revision_web")
    dias = (dt.date.today() - dt.date.fromisoformat(ultima)).days if ultima else None
    if marcar is not None:
        estado["ultima_revision_web"] = hoy()
        if marcar:
            estado.setdefault("notas_web", []).append(f"{hoy()}: {marcar}")
            estado["notas_web"] = estado["notas_web"][-12:]
        return {"marcado": hoy(), "toca": False}
    return {"ultima_revision_web": ultima, "dias": dias, "toca": dias is None or dias >= DIAS_WEB}


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Novedades de OrcaSlicer para el taller.")
    sub = ap.add_subparsers(dest="accion", required=True)
    g = sub.add_parser("gcode")
    g.add_argument("gcode", type=Path)
    p = sub.add_parser("perfiles")
    p.add_argument("rutas", type=Path, nargs="+")
    p.add_argument("--config", type=Path)
    p.add_argument("--maquinas", type=Path, nargs="*", default=[],
                   help="carpeta machine traída: sus copias de usuario cuentan como impresoras presentes")
    w = sub.add_parser("web")
    w.add_argument("--marcar", nargs="?", const="", help="anotar que se revisó hoy (con una nota opcional)")
    for s in (g, p, w):
        s.add_argument("--estado", type=Path, help="novedades-orca.json de la carpeta de trabajo")
        s.add_argument("--json", type=Path)
    a = ap.parse_args(argv)

    estado = cargar_estado(a.estado)
    hay = False
    if a.accion == "gcode":
        r = revisar_gcode(a.gcode, estado)
        print(f"Orca del G-code: {r['version_orca'] or 'desconocida'} (el taller conoce la {r['version_taller']})")
        if r["otra_version"]:
            print("  Es otra versión: revisar sus notas de versión antes de usar parámetros nuevos.")
        for titulo, clave in (("Parámetros nuevos que el taller no conoce", "claves_nuevas"),
                              ("Parámetros del taller que este Orca ya no tiene", "claves_quitadas")):
            if r[clave]:
                recientes = set(r[clave.replace("claves_", "") + "_desde_la_ultima_vez"])
                print(f"  {titulo} ({len(r[clave])}): "
                      + ", ".join(c + (" (nuevo)" if c in recientes else "") for c in r[clave][:30]))
        hay = r["otra_version"] or bool(r["nuevas_desde_la_ultima_vez"] or r["quitadas_desde_la_ultima_vez"])
        if not hay:
            print("  Sin novedades desde la última vez.")
    elif a.accion == "perfiles":
        config = comun.cargar_json(a.config) if a.config and a.config.exists() else None
        r = revisar_perfiles(a.rutas, config, a.maquinas)
        for nombre, claves in r["claves_que_orca_no_usa"].items():
            print(f"  {nombre}: claves que Orca {comun.VERSION_ORCA} ya no usa: {', '.join(claves)}")
        for t in r["test_viejos"]:
            print(f"  Perfil de calibración viejo: {t}")
        for n in r["auto_sin_impresora"]:
            print(f"  Perfil AUTO de una impresora que no está en la configuración: {n}")
        for n in r["ilegibles"]:
            print(f"  No pude leer: {n}")
        hay = any(r.values())
        if not hay:
            print("  Los perfiles están al día.")
    else:
        r = revisar_web(estado, a.marcar)
        if a.marcar is not None:
            print(f"Anotado: revisión en la web del {r['marcado']}.")
        elif r["toca"]:
            print("Toca revisar en la web si hay una versión nueva de Orca o plugins nuevos que sirvan "
                  f"(última revisión: {r['ultima_revision_web'] or 'nunca'}).")
            hay = True
        else:
            print(f"La última revisión en la web fue hace {r['dias']} días: no hace falta todavía.")
    if a.estado and not (a.accion == "web" and a.marcar is None):
        guardar_estado(a.estado, estado)
    if a.json:
        a.json.write_text(json.dumps(r, ensure_ascii=False, indent=2), encoding="utf-8")
    sys.exit(1 if hay else 0)


if __name__ == "__main__":
    main()
