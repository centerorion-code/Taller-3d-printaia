"""Datos de una impresora del taller (taller-3d/impresoras/<id>.json en la carpeta de trabajo).

El plugin no trae impresoras: Claude arma estos datos para la impresora en la que el usuario quiere
trabajar, con lo que usa su perfil de Orca (leído de un G-code laminado con ese perfil) y lo que
investiga en las fuentes oficiales (fabricante y perfiles de OrcaSlicer). Este script cubre lo que se
puede verificar sin adivinar:

  # Lo que usa Orca para esa impresora (área, altura, firmware, boquilla, velocidades) según un G-code
  python3 impresora.py desde-gcode prueba.gcode [--id mi-impresora] [--salida borrador.json]

  # Que los datos estén completos y sean razonables (límites del fabricante, fuentes, área)
  python3 impresora.py validar mi-impresora.json

  # Que los datos coincidan con lo que usa Orca de verdad (área, altura, firmware, boquilla, modelo)
  python3 impresora.py comparar mi-impresora.json prueba.gcode

Código de salida: 0 bien, 1 con diferencias o cosas por completar, 2 datos inválidos.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comun  # noqa: E402

RE_CLAVE = re.compile(r"^;\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$")
RE_VERSION = re.compile(r"generated by OrcaSlicer\s+([0-9][0-9A-Za-z.\-]*)")
TOLERANCIA_MM = 0.5


def leer_configuracion(ruta: Path) -> dict[str, str]:
    """Claves '; clave = valor' del bloque de configuración que Orca escribe al final del G-code."""
    claves: dict[str, str] = {}
    with open(ruta, encoding="utf-8", errors="replace") as f:
        for linea in f:
            m = RE_CLAVE.match(linea)
            if m:
                claves[m.group(1)] = m.group(2).strip().strip('"')
            elif "_version_orca" not in claves:
                v = RE_VERSION.search(linea)
                if v:
                    claves["_version_orca"] = v.group(1)
    return claves


def _primero(valor: str | None) -> float | None:
    if not valor:
        return None
    try:
        return float(str(valor).split(",")[0].strip())
    except ValueError:
        return None


def area_de(printable_area: str | None, printable_height: str | None) -> dict | None:
    """printable_area de Orca ('0x0,300x0,300x300,0x300') y printable_height → área del taller."""
    if not printable_area:
        return None
    puntos = []
    for par in printable_area.split(","):
        partes = par.strip().lower().split("x")
        if len(partes) != 2:
            return None
        try:
            puntos.append((float(partes[0]), float(partes[1])))
        except ValueError:
            return None
    altura = _primero(printable_height)
    if not puntos or altura is None:
        return None
    xs, ys = [p[0] for p in puntos], [p[1] for p in puntos]
    return {"x_min": min(xs), "x_max": max(xs), "y_min": min(ys), "y_max": max(ys), "z_max": altura}


def _id_de(texto: str) -> str:
    plano = unicodedata.normalize("NFKD", texto).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plano.lower()).strip("-") or "impresora"


def desde_gcode(ruta: Path, id_impresora: str | None = None) -> dict:
    """Borrador de los datos con lo que dice Orca. Los límites de temperatura, el cerramiento y las fuentes
    quedan pendientes: salen del fabricante, no del laminador."""
    cfg = leer_configuracion(ruta)
    modelo = cfg.get("printer_model", "")
    perfil = cfg.get("printer_settings_id", "")
    if not modelo and not perfil:
        raise SystemExit("El G-code no trae printer_model ni printer_settings_id: laminalo con Orca y el perfil "
                         "de máquina de la impresora.")
    corto = modelo.split(" ", 1)[1] if " " in modelo else modelo
    datos = {
        "id": id_impresora or _id_de(modelo or perfil),
        "nombre": modelo,
        "perfiles_maquina": [perfil] if perfil else [],
        "patron_perfiles": corto or None,
        "boquilla_mm": _primero(cfg.get("nozzle_diameter")),
        "firmware": cfg.get("gcode_flavor") or None,
        "cinematica": cfg.get("printer_structure") or None,
        "boquilla_tipo": cfg.get("nozzle_type") or None,
        "area": area_de(cfg.get("printable_area"), cfg.get("printable_height")),
        "margen_mm": 5,
        "limites": {
            "boquilla_max_c": None,
            "cama_max_c": None,
            "velocidad_max_mm_s": _primero(cfg.get("machine_max_speed_x")),
            "aceleracion_max_mm_s2": _primero(cfg.get("machine_max_acceleration_x")),
        },
        "cerramiento": None,
        "fuentes": [],
        "origen_orca": {"version": cfg.get("_version_orca") or None, "perfil_maquina": perfil or None},
    }
    datos["pendiente"] = pendientes(datos)
    return datos


def pendientes(datos: dict) -> list[str]:
    """Lo que falta investigar o preguntar (no se completa adivinando)."""
    faltan = []
    limites = datos.get("limites") or {}
    for clave in ("boquilla_max_c", "cama_max_c"):
        if limites.get(clave) is None:
            faltan.append(f"limites.{clave} (fabricante)")
    if datos.get("cerramiento") is None:
        faltan.append("cerramiento (fabricante)")
    if not datos.get("fuentes"):
        faltan.append("fuentes (enlaces oficiales)")
    if not datos.get("sistema"):
        faltan.append("sistema (perfiles de sistema de Orca para esta impresora)")
    if not datos.get("cama_sistema"):
        faltan.append("cama_sistema (temperaturas de cama de los filamentos de sistema)")
    return faltan


def validar(datos: dict) -> tuple[str, list[str], list[str]]:
    """(estado, problemas, avisos). Problemas: no se puede usar. Avisos: conviene completar."""
    problemas = comun.problemas_impresora(datos)
    avisos = []
    if isinstance(datos, dict):
        for falta in pendientes(datos):
            if falta.startswith(("sistema", "cama_sistema", "cerramiento")):
                avisos.append(f"falta {falta}")
        if datos.get("pendiente"):
            avisos.append("quedó la lista 'pendiente': sacala cuando esté todo completo")
        if not datos.get("perfiles_maquina") and not datos.get("patron_perfiles"):
            avisos.append("sin perfiles_maquina ni patron_perfiles: la revisión automática no la va a reconocer")
    estado = comun.RECHAZO if problemas else (comun.ADVERTENCIA if avisos else comun.APROBADO)
    return estado, problemas, avisos


def comparar(datos: dict, cfg: dict[str, str]) -> list[str]:
    """Diferencias entre los datos y lo que usó Orca al laminar."""
    difs = []
    modelo = cfg.get("printer_model")
    if modelo and datos.get("nombre") and modelo != datos["nombre"]:
        difs.append(f"modelo: datos '{datos['nombre']}', Orca '{modelo}'")
    perfil = cfg.get("printer_settings_id")
    if perfil and datos.get("perfiles_maquina") and perfil not in datos["perfiles_maquina"]:
        difs.append(f"perfil de máquina '{perfil}' no está en perfiles_maquina")
    area = area_de(cfg.get("printable_area"), cfg.get("printable_height"))
    if area and isinstance(datos.get("area"), dict):
        for clave, valor in area.items():
            propio = datos["area"].get(clave)
            if not isinstance(propio, (int, float)) or abs(float(propio) - valor) > TOLERANCIA_MM:
                difs.append(f"area.{clave}: datos {propio}, Orca {valor:g}")
    flavor = cfg.get("gcode_flavor")
    if flavor and datos.get("firmware") and flavor != datos["firmware"]:
        difs.append(f"firmware: datos '{datos['firmware']}', Orca '{flavor}'")
    boquilla = _primero(cfg.get("nozzle_diameter"))
    if boquilla is not None and isinstance(datos.get("boquilla_mm"), (int, float)) \
            and abs(boquilla - float(datos["boquilla_mm"])) > 0.001:
        difs.append(f"boquilla: datos {datos['boquilla_mm']} mm, Orca {boquilla:g} mm")
    return difs


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Datos de una impresora del taller.")
    sub = ap.add_subparsers(dest="accion", required=True)
    g = sub.add_parser("desde-gcode", help="borrador con lo que usa Orca, a partir de un G-code")
    g.add_argument("gcode", type=Path)
    g.add_argument("--id")
    g.add_argument("--salida", type=Path)
    v = sub.add_parser("validar", help="que los datos estén completos y sean razonables")
    v.add_argument("datos", type=Path)
    c = sub.add_parser("comparar", help="que los datos coincidan con lo que usó Orca")
    c.add_argument("datos", type=Path)
    c.add_argument("gcode", type=Path)
    a = ap.parse_args(argv)

    if a.accion == "desde-gcode":
        datos = desde_gcode(a.gcode, a.id)
        texto = json.dumps(datos, ensure_ascii=False, indent=2) + "\n"
        if a.salida:
            a.salida.write_text(texto, encoding="utf-8")
            print(f"Escrito: {a.salida}")
        else:
            print(texto, end="")
        print("Pendiente (investigar en fuentes oficiales o preguntar): " + "; ".join(datos["pendiente"]),
              file=sys.stderr)
        comun.salir(comun.ADVERTENCIA)

    try:
        datos = comun.cargar_json(a.datos)
    except (OSError, ValueError) as error:
        raise SystemExit(f"No pude leer {a.datos}: {error}")

    if a.accion == "validar":
        estado, problemas, avisos = validar(datos)
        print(f"RESULTADO: {comun.TITULO[estado]}")
        for p in problemas:
            print(f"  [RECHAZO] {p}")
        for x in avisos:
            print(f"  [ADVERTENCIA] {x}")
        comun.salir(estado)

    difs = comparar(datos, leer_configuracion(a.gcode))
    if difs:
        print("RESULTADO: CON DIFERENCIAS (lo que usa Orca no coincide con los datos)")
        for d in difs:
            print(f"  - {d}")
        comun.salir(comun.ADVERTENCIA)
    print("RESULTADO: COINCIDEN")
    comun.salir(comun.APROBADO)


if __name__ == "__main__":
    main()
