"""Datos de una impresora del taller (taller-3d/impresoras/<id>.json en la carpeta de trabajo).

El plugin no trae impresoras: Claude arma estos datos para la impresora en la que el usuario quiere
trabajar, con lo que usa su perfil de Orca (leído de un G-code laminado con ese perfil) y lo que
investiga en las fuentes oficiales (fabricante y perfiles de OrcaSlicer). Este script cubre lo que se
puede verificar sin adivinar:

  # Lo que usa Orca para esa impresora (área, altura, firmware, boquilla, velocidades) según un G-code
  python3 impresora.py desde-gcode prueba.gcode [--id mi-impresora] [--salida borrador.json]

  # Que los datos estén completos y sean razonables (límites del fabricante, fuentes, área)
  python3 impresora.py validar mi-impresora.json

  # Que los datos coincidan con lo que usa Orca de verdad (área, altura, firmware, boquilla, modelo)
  python3 impresora.py comparar mi-impresora.json prueba.gcode

  # Qué impresoras tiene el usuario en Orca: copias de usuario (carpeta machine), las que nombran
  # sus perfiles en compatible_printers y, si se leyó en la PC, la lista de Orca (models y la elegida)
  python3 impresora.py detectar --maquinas <machine> --perfiles <process> <filament> [--orca orca.json]

Código de salida: 0 bien, 1 con diferencias o cosas por completar, 2 datos inválidos.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comun  # noqa: E402

RE_BOQUILLA = comun.RE_BOQUILLA
LARGO_MINIMO_PATRON = 6
RE_CLAVE = re.compile(r"^;\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$")
RE_VERSION = re.compile(r"generated by OrcaSlicer\s+([0-9][0-9A-Za-z.\-]*)")
TOLERANCIA_MM = 0.5


def leer_configuracion(ruta: Path) -> dict[str, str]:
    """Claves '; clave = valor' del bloque de configuración que Orca escribe al final del G-code."""
    claves: dict[str, str] = {}
    with open(ruta, encoding="utf-8", errors="replace") as f:
        for linea in f:
            m = RE_CLAVE.match(linea)
            if m:
                claves[m.group(1)] = m.group(2).strip().strip('"')
            elif "_version_orca" not in claves:
                v = RE_VERSION.search(linea)
                if v:
                    claves["_version_orca"] = v.group(1)
    return claves


def _primero(valor: str | None) -> float | None:
    if not valor:
        return None
    try:
        return float(str(valor).split(",")[0].strip())
    except ValueError:
        return None


def area_de(printable_area: str | None, printable_height: str | None) -> dict | None:
    """printable_area de Orca ('0x0,300x0,300x300,0x300') y printable_height → área del taller."""
    if not printable_area:
        return None
    puntos = []
    for par in printable_area.split(","):
        partes = par.strip().lower().split("x")
        if len(partes) != 2:
            return None
        try:
            puntos.append((float(partes[0]), float(partes[1])))
        except ValueError:
            return None
    altura = _primero(printable_height)
    if not puntos or altura is None:
        return None
    xs, ys = [p[0] for p in puntos], [p[1] for p in puntos]
    return {"x_min": min(xs), "x_max": max(xs), "y_min": min(ys), "y_max": max(ys), "z_max": altura}


def patron_de(modelo: str) -> str | None:
    """Cómo aparece la impresora al final de los nombres de perfiles (@Modelo): el modelo completo, que no se
    confunde con otro ("Bambu Lab A1 mini", no "Lab A1 mini"; "Creality Hi", no "Hi"). Si los perfiles de sistema
    de Orca la nombran de otra forma, se cambia después de confirmarlo con esos nombres."""
    modelo = re.sub(r"\s+", " ", str(modelo or "")).strip()
    return modelo or None


def modelo_de_perfil(nombre: str) -> str:
    """'Creality Hi 0.4 nozzle' o 'Creality K1 (0.4 nozzle)' → el modelo, sin la boquilla."""
    return comun.modelo_de_perfil(nombre)


def _id_de(texto: str) -> str:
    plano = unicodedata.normalize("NFKD", texto).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", plano.lower()).strip("-") or "impresora"


def desde_gcode(ruta: Path, id_impresora: str | None = None) -> dict:
    """Borrador de los datos con lo que dice Orca. Los límites de temperatura, el cerramiento y las fuentes
    quedan pendientes: salen del fabricante, no del laminador."""
    cfg = leer_configuracion(ruta)
    modelo = cfg.get("printer_model", "")
    perfil = cfg.get("printer_settings_id", "")
    if not modelo and not perfil:
        raise SystemExit("El G-code no trae printer_model ni printer_settings_id: laminalo con Orca y el perfil "
                         "de máquina de la impresora.")
    datos = {
        "id": id_impresora or _id_de(modelo or perfil),
        "nombre": modelo,
        "perfiles_maquina": [perfil] if perfil else [],
        "patron_perfiles": patron_de(modelo),
        "boquilla_mm": _primero(cfg.get("nozzle_diameter")),
        "firmware": cfg.get("gcode_flavor") or None,
        "cinematica": cfg.get("printer_structure") or None,
        "boquilla_tipo": cfg.get("nozzle_type") or None,
        "area": area_de(cfg.get("printable_area"), cfg.get("printable_height")),
        "margen_mm": 5,
        "limites": {
            "boquilla_max_c": None,
            "cama_max_c": None,
            "velocidad_max_mm_s": _primero(cfg.get("machine_max_speed_x")),
            "aceleracion_max_mm_s2": _primero(cfg.get("machine_max_acceleration_x")),
        },
        "cerramiento": None,
        "fuentes": [],
        "origen_orca": {"version": cfg.get("_version_orca") or None, "perfil_maquina": perfil or None},
    }
    datos["pendiente"] = pendientes(datos)
    return datos


def pendientes(datos: dict) -> list[str]:
    """Lo que falta investigar o preguntar (no se completa adivinando)."""
    faltan = []
    limites = datos.get("limites") or {}
    for clave in ("boquilla_max_c", "cama_max_c"):
        if limites.get(clave) is None:
            faltan.append(f"limites.{clave} (fabricante)")
    if datos.get("cerramiento") is None:
        faltan.append("cerramiento (fabricante)")
    if not datos.get("fuentes"):
        faltan.append("fuentes (enlaces oficiales)")
    if not datos.get("sistema"):
        faltan.append("sistema (perfiles de sistema de Orca para esta impresora)")
    if not datos.get("cama_sistema"):
        faltan.append("cama_sistema (temperaturas de cama de los filamentos de sistema)")
    return faltan


def validar(datos: dict) -> tuple[str, list[str], list[str]]:
    """(estado, problemas, avisos). Problemas: no se puede usar. Avisos: conviene completar."""
    problemas = comun.problemas_impresora(datos)
    avisos = []
    if isinstance(datos, dict):
        for falta in pendientes(datos):
            if falta.startswith(("sistema", "cama_sistema", "cerramiento")):
                avisos.append(f"falta {falta}")
        if datos.get("pendiente"):
            avisos.append("quedó la lista 'pendiente': sacala cuando esté todo completo")
        if not datos.get("perfiles_maquina") and not datos.get("patron_perfiles"):
            avisos.append("sin perfiles_maquina ni patron_perfiles: la revisión automática no la va a reconocer")
        patron = str(datos.get("patron_perfiles") or "")
        if patron and len(patron) < LARGO_MINIMO_PATRON:
            avisos.append(f"patron_perfiles '{patron}' es muy corto y se puede confundir con otros perfiles: "
                          "usá el modelo completo")
    estado = comun.RECHAZO if problemas else (comun.ADVERTENCIA if avisos else comun.APROBADO)
    return estado, problemas, avisos


def comparar(datos: dict, cfg: dict[str, str]) -> list[str]:
    """Diferencias entre los datos y lo que usó Orca al laminar."""
    difs = []
    modelo = cfg.get("printer_model")
    if modelo and datos.get("nombre") and modelo != datos["nombre"]:
        difs.append(f"modelo: datos '{datos['nombre']}', Orca '{modelo}'")
    perfil = cfg.get("printer_settings_id")
    if perfil and datos.get("perfiles_maquina") and perfil not in datos["perfiles_maquina"]:
        difs.append(f"perfil de máquina '{perfil}' no está en perfiles_maquina")
    area = area_de(cfg.get("printable_area"), cfg.get("printable_height"))
    if area and isinstance(datos.get("area"), dict):
        for clave, valor in area.items():
            propio = datos["area"].get(clave)
            if not isinstance(propio, (int, float)) or abs(float(propio) - valor) > TOLERANCIA_MM:
                difs.append(f"area.{clave}: datos {propio}, Orca {valor:g}")
    flavor = cfg.get("gcode_flavor")
    if flavor and datos.get("firmware") and flavor != datos["firmware"]:
        difs.append(f"firmware: datos '{datos['firmware']}', Orca '{flavor}'")
    boquilla = _primero(cfg.get("nozzle_diameter"))
    if boquilla is not None and isinstance(datos.get("boquilla_mm"), (int, float)) \
            and abs(boquilla - float(datos["boquilla_mm"])) > 0.001:
        difs.append(f"boquilla: datos {datos['boquilla_mm']} mm, Orca {boquilla:g} mm")
    return difs


def _jsons(rutas) -> list[Path]:
    archivos = []
    for ruta in rutas or []:
        ruta = Path(ruta)
        archivos += sorted(ruta.glob("*.json")) if ruta.is_dir() else ([ruta] if ruta.suffix == ".json" else [])
    return archivos


def _lista(valor, numeros: bool = False) -> list[str]:
    """Una lista de Orca ("a;b" o ["a", "b"]) como textos limpios. Con numeros=True acepta también números."""
    if isinstance(valor, str):
        valor = re.split(r"[;\n]", valor)
    if not isinstance(valor, list):
        return []
    tipos = (str, int, float) if numeros else (str,)
    return [str(v).strip().strip('"').strip() for v in valor
            if isinstance(v, tipos) and not isinstance(v, bool) and str(v).strip().strip('"').strip()]


def _boquillas_de(nombre: str) -> set[str]:
    return {b.replace(",", ".") for b in comun.RE_NUMERO_BOQUILLA.findall(str(nombre or ""))}


def detectar(maquinas=None, perfiles=None, orca: dict | None = None) -> list[dict]:
    """Impresoras del usuario según lo que se ve sin pedir nada nuevo. Agrupa por modelo (sin distinguir
    mayúsculas) y dice de dónde salió: copia de usuario (la única que orca-mcp puede usar para laminar), perfiles
    del usuario (compatible_printers), perfiles AUTO del taller (por su nombre) o la lista de Orca (models de
    OrcaSlicer.conf, leída en la PC). inherits solo
    se usa en las copias de usuario, siguiendo copias de copias hasta el perfil de sistema."""
    encontradas: dict[str, dict] = {}

    def entrada(modelo: str, preferido: bool = False) -> dict:
        e = encontradas.setdefault(comun.plano(modelo), {"modelo": modelo, "perfiles_sistema": set(),
                                                         "copias_usuario": [], "boquillas": set(), "fuentes": set(),
                                                         "seleccionada": False})
        if preferido or (e["modelo"] == e["modelo"].lower() and modelo != modelo.lower()):
            e["modelo"] = modelo
        return e

    copias: dict[str, str] = {}
    for archivo in _jsons(maquinas):
        try:
            datos = comun.cargar_json(archivo)
        except (OSError, ValueError):
            continue
        if not isinstance(datos, dict):
            continue
        nombre = datos.get("name") if isinstance(datos.get("name"), str) and datos["name"].strip() else archivo.stem
        hereda = datos.get("inherits") if isinstance(datos.get("inherits"), str) else ""
        copias[nombre.strip()] = hereda.strip()

    def sistema_de(nombre: str) -> str:
        """El perfil de sistema del que sale una copia (sigue copias de copias)."""
        vistos = set()
        while nombre in copias and copias[nombre] and nombre not in vistos:
            vistos.add(nombre)
            nombre = copias[nombre]
        return nombre

    for nombre, hereda in copias.items():
        base = sistema_de(nombre)
        e = entrada(modelo_de_perfil(base if hereda else nombre))
        e["copias_usuario"].append(nombre)
        if hereda and base not in copias:
            e["perfiles_sistema"].add(base)
        e["boquillas"] |= _boquillas_de(nombre) | _boquillas_de(base)
        e["fuentes"].add("copia de usuario")
    autos: list[str] = []
    for archivo in _jsons(perfiles):
        try:
            datos = comun.cargar_json(archivo)
        except (OSError, ValueError):
            continue
        propio = datos.get("name") if isinstance(datos, dict) and isinstance(datos.get("name"), str) else archivo.stem
        auto = comun.RE_AUTO.match(propio.strip())
        if auto and auto.group(1).strip():
            autos.append(auto.group(1).strip())
        for nombre in _lista(datos.get("compatible_printers") if isinstance(datos, dict) else None):
            if nombre in copias:
                continue
            e = entrada(modelo_de_perfil(nombre))
            e["perfiles_sistema"].add(nombre)
            e["boquillas"] |= _boquillas_de(nombre)
            e["fuentes"].add("perfiles del usuario")
    modelos = (orca or {}).get("models") if isinstance(orca, dict) else None
    if isinstance(modelos, dict):
        modelos = [modelos]
    for m in modelos if isinstance(modelos, list) else []:
        modelo = m.get("model") if isinstance(m, dict) and isinstance(m.get("model"), str) else ""
        if not modelo.strip():
            continue
        e = entrada(modelo.strip(), preferido=True)
        e["fuentes"].add("instalada en Orca")
        e["boquillas"] |= {b.replace(",", ".") for b in _lista(m.get("nozzle_diameter"), numeros=True)}
    elegida = (orca or {}).get("machine") if isinstance(orca, dict) else None
    if isinstance(elegida, str) and elegida.strip():
        elegida = elegida.strip()
        e = entrada(modelo_de_perfil(sistema_de(elegida) if elegida in copias else elegida))
        e["seleccionada"] = True
        e["fuentes"].add("elegida en la ventana de Orca")
    # Los AUTO del taller ("AUTO proceso @Creality Hi") dicen que esa impresora se preparó, aunque sea en otra
    # carpeta de trabajo y aunque sus perfiles no la nombren en compatible_printers ni esté conectada machine.
    for patron in autos:
        e = next((x for x in encontradas.values() if comun.mismo_modelo(x["modelo"], patron)), None) or entrada(patron)
        e["fuentes"].add("perfiles AUTO del taller")
    salida = []
    for e in encontradas.values():
        salida.append({**e, "perfiles_sistema": sorted(e["perfiles_sistema"]), "boquillas": sorted(e["boquillas"]),
                       "fuentes": sorted(e["fuentes"])})
    return sorted(salida, key=lambda e: (not e["seleccionada"], not e["copias_usuario"], e["modelo"].lower()))


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Datos de una impresora del taller.")
    sub = ap.add_subparsers(dest="accion", required=True)
    g = sub.add_parser("desde-gcode", help="borrador con lo que usa Orca, a partir de un G-code")
    g.add_argument("gcode", type=Path)
    g.add_argument("--id")
    g.add_argument("--salida", type=Path)
    v = sub.add_parser("validar", help="que los datos estén completos y sean razonables")
    v.add_argument("datos", type=Path)
    c = sub.add_parser("comparar", help="que los datos coincidan con lo que usó Orca")
    c.add_argument("datos", type=Path)
    c.add_argument("gcode", type=Path)
    d = sub.add_parser("detectar", help="qué impresoras tiene el usuario en Orca")
    d.add_argument("--maquinas", type=Path, nargs="*", default=[], help="carpeta machine traída (copias de usuario)")
    d.add_argument("--perfiles", type=Path, nargs="*", default=[], help="carpetas process y filament traídas")
    d.add_argument("--orca", type=Path, help="JSON con models y machine, sacado de OrcaSlicer.conf en la PC")
    d.add_argument("--json", type=Path)
    a = ap.parse_args(argv)

    if a.accion == "detectar":
        orca = None
        if a.orca:
            try:
                orca = comun.cargar_json(a.orca)
            except (OSError, ValueError) as error:
                raise SystemExit(f"No pude leer {a.orca} ({error}). Tiene que ser la salida del comando de "
                                 "references/impresoras.md, guardada como JSON.")
            if not isinstance(orca, dict):
                raise SystemExit(f"{a.orca} no tiene el formato esperado (un objeto con models y machine).")
        lista = detectar(a.maquinas, a.perfiles, orca)
        if a.json:
            a.json.write_text(json.dumps(lista, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        if not lista:
            print("No se ve ninguna impresora: preguntale al usuario cuáles tiene.")
        for e in lista:
            marcas = []
            if e["seleccionada"]:
                marcas.append("elegida en Orca")
            marcas.append("con copia de usuario: " + ", ".join(e["copias_usuario"]) if e["copias_usuario"]
                          else "sin copia de usuario")
            print(f"- {e['modelo']} ({'; '.join(marcas)}) [{', '.join(e['fuentes'])}]")
        comun.salir(comun.APROBADO)

    if a.accion == "desde-gcode":
        datos = desde_gcode(a.gcode, a.id)
        texto = json.dumps(datos, ensure_ascii=False, indent=2) + "\n"
        if a.salida:
            a.salida.write_text(texto, encoding="utf-8")
            print(f"Escrito: {a.salida}")
        else:
            print(texto, end="")
        print("Pendiente (investigar en fuentes oficiales o preguntar): " + "; ".join(datos["pendiente"]),
              file=sys.stderr)
        comun.salir(comun.ADVERTENCIA)

    try:
        datos = comun.cargar_json(a.datos)
    except (OSError, ValueError) as error:
        raise SystemExit(f"No pude leer {a.datos}: {error}")

    if a.accion == "validar":
        estado, problemas, avisos = validar(datos)
        print(f"RESULTADO: {comun.TITULO[estado]}")
        for p in problemas:
            print(f"  [RECHAZO] {p}")
        for x in avisos:
            print(f"  [ADVERTENCIA] {x}")
        comun.salir(estado)

    difs = comparar(datos, leer_configuracion(a.gcode))
    if difs:
        print("RESULTADO: CON DIFERENCIAS (lo que usa Orca no coincide con los datos)")
        for d in difs:
            print(f"  - {d}")
        comun.salir(comun.ADVERTENCIA)
    print("RESULTADO: COINCIDEN")
    comun.salir(comun.APROBADO)


if __name__ == "__main__":
    main()
