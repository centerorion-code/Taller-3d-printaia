"""Arma el proyecto de OrcaSlicer (.3mf) de una pieza: el modelo con los perfiles y la cama elegidos.

orca-mcp lamina por línea de comandos y no exporta proyectos. Este script arma el proyecto con lo
mismo que usó Orca: el STL de la pieza y la configuración completa que Orca escribe al final del
G-code (los nombres de los perfiles y todos sus valores). Al abrirlo con doble clic, Orca muestra la
pieza en el centro de la cama con la impresora, el filamento y el proceso elegidos, y el tipo de cama
real (por línea de comandos Orca usa Cool Plate). Como los valores van dentro del proyecto, sirve
aunque Orca no haya visto todavía los perfiles nuevos.

Uso:
  python3 proyecto_3mf.py --stl pieza.stl --gcode <G-code de la pieza> --cama "Textured PEI Plate" \\
      --salida <nombre>.3mf [--nombre "Soporte del router"] [--json informe_3mf.json]

El formato es el de Orca 2.5.1 (datos/proyecto-3mf-2.5.1.json, sacado de un proyecto que exportó
Orca). No lleva G-code: para imprimir se usa el G-code revisado.

Código de salida: 0 listo, 1 listo con avisos, 2 no se pudo armar.
"""
