RE_CLAVE = re.compile(r"^; ([A-Za-z0-9_]+) = (.*)$")
RE_VERSION = re.compile(r"generated by OrcaSlicer\s+([0-9][0-9A-Za-z.\-]*)")
# Claves que Orca ejecuta al laminar: un archivo que escribe Claude no las lleva (regla 3).
QUE_EJECUTAN = ("post_process", "plugins", "slicing_pipeline_plugin")


class ErrorProyecto(Exception):
    pass


# ---------------------------------------------------------------- lectura

def leer_stl(ruta: Path):
    """Vértices únicos y triángulos de un STL binario o de texto."""
    import numpy as np

    datos = ruta.read_bytes()
    if len(datos) < 84:
        raise ErrorProyecto(f"{ruta.name} no es un STL (muy corto).")
    cantidad = struct.unpack_from("<I", datos, 80)[0]
    if 84 + 50 * cantidad == len(datos):
        registros = np.frombuffer(datos, dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]),
                                  count=cantidad, offset=84)
        puntos = registros["v"].reshape(-1, 3).astype(np.float64)
    else:
        texto = datos.decode("utf-8", "replace")
        if not texto.lstrip().lower().startswith("solid"):
            raise ErrorProyecto(f"{ruta.name} no es un STL (ni binario ni de texto).")
        numeros = re.findall(r"^\s*vertex\s+(\S+)\s+(\S+)\s+(\S+)", texto, re.M)
        puntos = np.array(numeros, dtype=np.float64)
    if len(puntos) < 3 or len(puntos) % 3:
        raise ErrorProyecto(f"{ruta.name} no tiene triángulos.")
    if not np.isfinite(puntos).all():
        raise ErrorProyecto(f"{ruta.name} tiene coordenadas inválidas.")
    vertices, indices = np.unique(puntos.astype(np.float32), axis=0, return_inverse=True)
    triangulos = indices.reshape(-1, 3)
    validos = (triangulos[:, 0] != triangulos[:, 1]) & (triangulos[:, 1] != triangulos[:, 2]) & \
              (triangulos[:, 0] != triangulos[:, 2])
    return vertices.astype(np.float64), triangulos[validos]


def leer_config_gcode(ruta: Path) -> tuple[dict[str, str], str | None]:
    """Claves del bloque de configuración que Orca escribe al final del G-code (la última si se repite)."""
    claves: dict[str, str] = {}
    version = None
    dentro = False
    with open(ruta, encoding="utf-8", errors="replace") as f:
        for linea in f:
            if version is None:
                v = RE_VERSION.search(linea)
                if v:
                    version = v.group(1)
